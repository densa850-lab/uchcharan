function period(h24) {
  if (h24 >= 4 && h24 < 12) return 'सकाळी';
  if (h24 >= 12 && h24 < 16) return 'दुपारी';
  if (h24 >= 16 && h24 < 20) return 'संध्याकाळी';
  return 'रात्री';
}

