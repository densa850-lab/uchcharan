function period(h24) {
  if (h24 >= 4 && h24 < 12) return 'सुबह';
  if (h24 >= 12 && h24 < 16) return 'दोपहर';
  if (h24 >= 16 && h24 < 20) return 'शाम';
  return 'रात';
}

